const TWO_CHAR_SURNAMES = [
  '欧阳','司马','上官','诸葛','慕容','司徒','令狐','公孙','仲孙','轩辕',
  '高楼','夏侯'
];

function getStroke(char) {
  const s = STROKES[char];
  return typeof s === 'number' ? s : null;
}

function getWuxing(n) {
  if (!n || n <= 0) return '';
  const r = n % 10;
  if (r === 1 || r === 2) return '木';
  if (r === 3 || r === 4) return '火';
  if (r === 5 || r === 6) return '土';
  if (r === 7 || r === 8) return '金';
  return '水';
}

function calcFiveGrids(name) {
  const chars = [...name];
  const firstTwo = name.slice(0, 2);
  let surname, givenName;

  if (TWO_CHAR_SURNAMES.includes(firstTwo)) {
    surname = firstTwo;
    givenName = name.slice(2);
  } else {
    surname = chars[0] || '';
    givenName = name.slice(1);
  }

  const s1 = getStroke(surname[0]) || 0;
  const s2 = surname[1] ? (getStroke(surname[1]) || 0) : 0;
  const gn = [...givenName];
  const g1 = gn[0] ? (getStroke(gn[0]) || 0) : 0;
  const g2 = gn[1] ? (getStroke(gn[1]) || 0) : 0;

  // 天格：单姓+1 或 复姓笔画合计
  const tiange = s1 + s2 + (surname.length === 1 ? 1 : 0);
  // 地格：单名+1 或 双名笔画合计
  const dige = g1 + g2 + (givenName.length === 1 ? 1 : 0);
  // 人格：姓首笔+名1
  const renge = s1 + g1;
  // 总格：全部笔画
  const zongge = s1 + s2 + g1 + g2;
  // 外格：总格-人格+1
  const waige = zongge - renge + 1;

  return {
    tiange, dige, renge, zongge, waige,
    surname, givenName,
    tiangeEl: getWuxing(tiange),
    digeEl: getWuxing(dige),
    rengeEl: getWuxing(renge),
    zonggeEl: getWuxing(zongge),
    waigeEl: getWuxing(waige)
  };
}

function analyzeName(name, gender) {
  const g = calcFiveGrids(name);
  const { tiange, dige, renge, zongge, waige, surname, givenName,
    tiangeEl, digeEl, rengeEl, zonggeEl, waigeEl } = g;

  const els = [tiangeEl, digeEl, rengeEl, zonggeEl].filter(Boolean);
  const cnt = { 木: 0, 火: 0, 土: 0, 金: 0, 水: 0 };
  els.forEach(function(e) { if (e) cnt[e]++; });

  const vals = Object.values(cnt);
  const max = Math.max.apply(null, vals);
  const balance = (max <= 2 && vals.filter(function(v) { return v > 0; }).length >= 3) ? '均衡' : '偏颇';

  // 综合评分
  const score = Math.round(renge * 0.4 + tiange * 0.2 + dige * 0.2 + zongge * 0.2);
  const total = Math.min(100, Math.max(0, score));

  const grade = total >= 90 ? '大吉' : total >= 80 ? '吉' : total >= 70 ? '中吉' : total >= 60 ? '中' : total >= 50 ? '平' : '凶';
  const gradeColor = total >= 80 ? '#4ade80' : total >= 60 ? '#fbbf24' : '#f87171';

  return {
    name: name,
    surname: surname,
    givenName: givenName,
    gender: gender || '男',
    total: total,
    grade: grade,
    gradeColor: gradeColor,
    grids: {
      tiange: { value: tiange, el: tiangeEl, label: '天格' },
      dige:   { value: dige,   el: digeEl,   label: '地格' },
      renge:  { value: renge,  el: rengeEl,  label: '人格' },
      zongge: { value: zongge, el: zonggeEl, label: '总格' },
      waige:  { value: waige,  el: waigeEl,  label: '外格' },
    },
    wuxing: cnt,
    wuxingBalance: balance,
    comment: surname + givenName + '｜人格' + renge + '划(' + rengeEl + '气)，天格' + tiange + '划(' + tiangeEl + '气)，地格' + dige + '划(' + digeEl + '气)，总格' + zongge + '划(' + zonggeEl + '气)。五行' + balance + '。综合评分' + total + '分（' + grade + '）'
  };
}

